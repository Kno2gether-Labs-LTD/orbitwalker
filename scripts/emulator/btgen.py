"""btgen.py <out.json> <script>: script is ';'-separated steps:
   wait:MS | key:USAGE[:MODS] | text:STRING (digits/lowercase) | move:DX:DY:N | click | rclick | wheel:N | down | up"""
import json, sys
kb = [0x05,0x01,0x09,0x06,0xA1,0x01,0x85,0x01,0x05,0x07,0x19,0xE0,0x29,0xE7,0x15,0x00,0x25,0x01,0x75,0x01,0x95,0x08,0x81,0x02,
      0x95,0x01,0x75,0x08,0x81,0x01,0x95,0x06,0x75,0x08,0x15,0x00,0x25,0x65,0x05,0x07,0x19,0x00,0x29,0x65,0x81,0x00,0xC0]
ms = [0x05,0x01,0x09,0x02,0xA1,0x01,0x85,0x02,0x09,0x01,0xA1,0x00,0x05,0x09,0x19,0x01,0x29,0x03,0x15,0x00,0x25,0x01,0x95,0x03,0x75,0x01,0x81,0x02,
      0x95,0x01,0x75,0x05,0x81,0x01,0x05,0x01,0x09,0x30,0x09,0x31,0x09,0x38,0x15,0x81,0x25,0x7F,0x75,0x08,0x95,0x03,0x81,0x06,0xC0,0xC0]
c = [{"id":1,"command":"register","name":"Test BT Keyboard Mouse","vid":1452,"pid":615,"bus":"bluetooth","descriptor":kb+ms}]
def d(ms): c.append({"id":1,"command":"delay","duration":ms})
def rep(r): c.append({"id":1,"command":"report","report":r})
def usage(ch):
    if ch.isdigit(): return 39 if ch == '0' else 29 + int(ch)
    if ch.isalpha(): return 4 + ord(ch.lower()) - 97
    if ch == ' ': return 44
    raise ValueError(ch)
btn = 0
for step in sys.argv[2].split(';'):
    p = step.split(':'); k = p[0]
    if k == 'wait': d(int(p[1]))
    elif k == 'key': rep([1, int(p[2]) if len(p) > 2 else 0, 0, int(p[1]), 0,0,0,0,0]); d(40); rep([1,0,0,0,0,0,0,0,0]); d(60)
    elif k == 'text':
        for ch in p[1]: rep([1, 0x02 if ch.isupper() else 0, 0, usage(ch), 0,0,0,0,0]); d(30); rep([1,0,0,0,0,0,0,0,0]); d(40)
    elif k == 'move':
        for _ in range(int(p[3])): rep([2, btn, int(p[1]) & 0xFF, int(p[2]) & 0xFF, 0]); d(16)
    elif k == 'down': btn = 1; rep([2,1,0,0,0]); d(40)
    elif k == 'up': btn = 0; rep([2,0,0,0,0]); d(40)
    elif k == 'click': rep([2,1,0,0,0]); d(60); rep([2,0,0,0,0]); d(60)
    elif k == 'rclick': rep([2,2,0,0,0]); d(60); rep([2,0,0,0,0]); d(60)
    elif k == 'wheel': rep([2,0,0,0,int(p[1]) & 0xFF]); d(60)
open(sys.argv[1], 'w').write('\n'.join(json.dumps(x) for x in c))
